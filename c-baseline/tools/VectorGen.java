// Cross-check vectors between the Java harness classes (Bouncy Castle) and the C baseline.
//
//   java -cp "<crypto-desktop lib dir>/*" tools/VectorGen.java gen vectors.txt
//   crypto-c selftest vectors.txt c2java.txt
//   java -cp "<crypto-desktop lib dir>/*" tools/VectorGen.java verify c2java.txt
//
// The lib dir is desktop/build/install/crypto-desktop/lib (crypto-desktop.jar, bcprov, kotlin-stdlib).
// "gen" uses exactly the classes DesktopMain uses (AES, AESGcm, ChaCha20Cipher, RsaLite,
// ElGamalLite, BcLwcAead + LwcSpecs) with fixed keys/nonces for the deterministic algorithms.
// "verify" decrypts what the C baseline produced and checks it gives the plaintext back.
import com.example.energy.AES;
import com.example.energy.AESGcm;
import com.example.energy.chacha20.ChaCha20Cipher;
import com.example.energy.elgamal.ElGamalLite;
import com.example.energy.lwc.AeadSpec;
import com.example.energy.lwc.BcLwcAead;
import com.example.energy.lwc.LwcSpecs;
import com.example.energy.rsa.RsaLite;
import org.bouncycastle.crypto.AsymmetricCipherKeyPair;
import org.bouncycastle.crypto.engines.*;
import org.bouncycastle.crypto.modes.AEADCipher;
import org.bouncycastle.crypto.params.*;
import org.bouncycastle.crypto.util.PrivateKeyFactory;
import org.bouncycastle.crypto.util.PrivateKeyInfoFactory;
import org.bouncycastle.util.encoders.Hex;

import java.io.PrintWriter;
import java.math.BigInteger;
import java.nio.file.Files;
import java.nio.file.Path;
import java.security.SecureRandom;
import java.util.Arrays;
import java.util.function.Supplier;

public class VectorGen {
    static final int[] LENGTHS = {0, 1, 15, 16, 17, 31, 32, 33, 63, 64, 65, 100, 1000, 4096};
    static final String PATTERN = "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789";
    // the prime that ElGamalLite.kt hard-coded before (RFC 2409 group 1, 768 bits)
    static final BigInteger P768 = new BigInteger(
        "FFFFFFFFFFFFFFFFC90FDAA22168C234C4C6628B80DC1CD1" +
        "29024E088A67CC74020BBEA63B139B22514A08798E3404DD" +
        "EF9519B3CD3A431B302B0A6DF25F14374FE1356D6D51C245" +
        "E485B576625E7EC6F44C42E9A63A3620FFFFFFFFFFFFFFFF", 16);

    static String plain(int n) {
        StringBuilder b = new StringBuilder(n);
        for (int i = 0; i < n; i++) b.append(PATTERN.charAt(i % 36));
        return b.toString();
    }

    record Lwc(String name, AeadSpec spec, Supplier<AEADCipher> engine) {}

    static Lwc[] lwcs() {
        LwcSpecs s = LwcSpecs.INSTANCE;
        return new Lwc[] {
            new Lwc("ascon", s.getASCON_128(), AsconAEAD128::new),
            new Lwc("elephant", s.getELEPHANT(), () -> new ElephantEngine(ElephantEngine.ElephantParameters.elephant200)),
            new Lwc("giftcofb", s.getGIFT_COFB(), GiftCofbEngine::new),
            new Lwc("grain128", s.getGRAIN128(), Grain128AEADEngine::new),
            new Lwc("xoodyak", s.getXOODYAK(), XoodyakEngine::new),
        };
    }

    static byte[] rnd(SecureRandom r, int n) { byte[] b = new byte[n]; r.nextBytes(b); return b; }
    static byte[] cat(byte[] a, byte[] b) { byte[] c = Arrays.copyOf(a, a.length + b.length); System.arraycopy(b, 0, c, a.length, b.length); return c; }

    static void gen(Path out) throws Exception {
        SecureRandom r = new SecureRandom();
        // the old hard-coded ElGamalLite prime must be exactly the standard 768-bit group
        System.out.println("ElGamal 768 group == original ElGamalLite P: " + ElGamalLite.INSTANCE.params(768).getP().equals(P768));
        int[] rsaBits = {1024, 2048, 3072, 4096}, egBits = {768, 1024, 2048, 3072, 4096};
        String[] rsaDer = new String[rsaBits.length];
        AsymmetricCipherKeyPair[] rsa = new AsymmetricCipherKeyPair[rsaBits.length];
        for (int i = 0; i < rsaBits.length; i++) {
            rsa[i] = RsaLite.INSTANCE.generateKeyPair(rsaBits[i]);
            rsaDer[i] = Hex.toHexString(PrivateKeyInfoFactory.createPrivateKeyInfo(rsa[i].getPrivate()).getEncoded());
        }
        AsymmetricCipherKeyPair[] eg = new AsymmetricCipherKeyPair[egBits.length];
        for (int i = 0; i < egBits.length; i++) eg[i] = ElGamalLite.INSTANCE.generateKeyPair(egBits[i]);
        try (PrintWriter w = new PrintWriter(Files.newBufferedWriter(out))) {
            w.println("# generated by tools/VectorGen.java from the Java harness classes");
            for (int len : LENGTHS) {
                String p = plain(len);
                byte[] key = rnd(r, 32), iv16 = rnd(r, 16), iv12 = rnd(r, 12);
                for (String[] v : new String[][] {{"aes", "32"}, {"aes128", "16"}, {"aes192", "24"}, {"aes256", "32"}}) {
                    byte[] k = Arrays.copyOf(key, Integer.parseInt(v[1]));
                    w.printf("vec|%s|%d|%s|%s|%s%n", v[0], len, Hex.toHexString(k), Hex.toHexString(iv16), AES.INSTANCE.encrypt(p, k, iv16));
                }
                for (String[] v : new String[][] {{"aesgcm", "32"}, {"aesgcm128", "16"}, {"aesgcm192", "24"}, {"aesgcm256", "32"}}) {
                    byte[] k = Arrays.copyOf(key, Integer.parseInt(v[1]));
                    w.printf("vec|%s|%d|%s|%s|%s%n", v[0], len, Hex.toHexString(k), Hex.toHexString(iv12), AESGcm.INSTANCE.encrypt(p, k, iv12));
                }
                w.printf("vec|chacha20|%d|%s|%s|%s%n", len, Hex.toHexString(key), Hex.toHexString(iv12), ChaCha20Cipher.INSTANCE.encrypt(p, key, iv12));
                for (Lwc l : lwcs()) {
                    byte[] k = rnd(r, l.spec().getKeyBytes()), n = rnd(r, l.spec().getNonceBytes());
                    w.printf("vec|%s|%d|%s|%s|%s%n", l.name(), len, Hex.toHexString(k), Hex.toHexString(n),
                        BcLwcAead.INSTANCE.encryptUtf8(l.engine().get(), l.spec(), p, k, n, null));
                }
                // hybrids, exactly as DesktopMain: AES.encrypt(plain, key, iv) + wrap(key || iv)
                for (int i = 0; i < rsaBits.length; i++) {
                    byte[] hk = rnd(r, 32), hiv = rnd(r, 16);
                    w.printf("rsa|%d|%s|%s|%s%n", len, rsaDer[i],
                        Hex.toHexString(RsaLite.INSTANCE.encryptSmall(cat(hk, hiv), (RSAKeyParameters) rsa[i].getPublic())), AES.INSTANCE.encrypt(p, hk, hiv));
                }
                for (int i = 0; i < egBits.length; i++) {
                    byte[] hk = rnd(r, 32), hiv = rnd(r, 16);
                    String x = ((ElGamalPrivateKeyParameters) eg[i].getPrivate()).getX().toString(16);
                    w.printf("elgamal|%d|%d|%s|%s|%s%n", egBits[i], len, x,
                        Hex.toHexString(ElGamalLite.INSTANCE.encryptSmall(cat(hk, hiv), (ElGamalPublicKeyParameters) eg[i].getPublic())), AES.INSTANCE.encrypt(p, hk, hiv));
                }
            }
        }
        System.out.println("wrote " + out);
    }

    static void verify(Path in) throws Exception {
        int pass = 0, fail = 0;
        for (String line : Files.readAllLines(in)) {
            if (line.isBlank() || line.startsWith("#")) continue;
            String[] f = line.split("\\|", -1);
            String got, what;
            int len;
            try {
                switch (f[0]) {
                    case "vec" -> {
                        len = Integer.parseInt(f[2]);
                        byte[] key = Hex.decode(f[3]), iv = Hex.decode(f[4]);
                        what = f[1];
                        got = switch (f[1]) {
                            case "aes", "aes128", "aes192", "aes256" -> AES.INSTANCE.decrypt(f[5], key, iv);
                            case "aesgcm", "aesgcm128", "aesgcm192", "aesgcm256" -> AESGcm.INSTANCE.decrypt(f[5], key);
                            case "chacha20" -> ChaCha20Cipher.INSTANCE.decrypt(f[5], key, iv);
                            default -> {
                                Lwc l = Arrays.stream(lwcs()).filter(x -> x.name().equals(f[1])).findFirst().orElseThrow();
                                yield BcLwcAead.INSTANCE.decryptUtf8(l.engine().get(), l.spec(), f[5], key, null);
                            }
                        };
                    }
                    case "rsa" -> {
                        len = Integer.parseInt(f[1]);
                        RSAKeyParameters priv = (RSAKeyParameters) PrivateKeyFactory.createKey(Hex.decode(f[2]));
                        what = "rsa" + priv.getModulus().bitLength();
                        byte[] hk = RsaLite.INSTANCE.decryptSmall(Hex.decode(f[3]), priv);
                        got = AES.INSTANCE.decrypt(f[4], Arrays.copyOfRange(hk, 0, 32), Arrays.copyOfRange(hk, 32, 48));
                    }
                    case "elgamal" -> {
                        int bits = Integer.parseInt(f[1]);
                        len = Integer.parseInt(f[2]);
                        what = "elgamal" + bits;
                        ElGamalPrivateKeyParameters priv = new ElGamalPrivateKeyParameters(new BigInteger(f[3], 16), ElGamalLite.INSTANCE.params(bits));
                        byte[] hk = ElGamalLite.INSTANCE.decryptSmall(Hex.decode(f[4]), priv);
                        got = AES.INSTANCE.decrypt(f[5], Arrays.copyOfRange(hk, 0, 32), Arrays.copyOfRange(hk, 32, 48));
                    }
                    default -> throw new IllegalArgumentException("bad line: " + f[0]);
                }
            } catch (Exception e) {
                System.out.printf("FAIL  %-9s %s%n", f[0].equals("vec") ? f[1] : f[0], e);
                fail++;
                continue;
            }
            boolean ok = got.equals(plain(len));
            System.out.printf("%s  %-9s len %5d: Java %s the C output%n", ok ? "PASS" : "FAIL", what, len, ok ? "decrypts" : "MISDECRYPTS");
            if (ok) pass++; else fail++;
        }
        System.out.printf("verify: %d passed, %d failed%n", pass, fail);
        if (fail > 0) System.exit(1);
    }

    public static void main(String[] args) throws Exception {
        if (args.length == 2 && args[0].equals("gen")) gen(Path.of(args[1]));
        else if (args.length == 2 && args[0].equals("verify")) verify(Path.of(args[1]));
        else { System.err.println("usage: VectorGen gen <out.txt> | verify <c2java.txt>"); System.exit(2); }
    }
}
